// MARK: - PartTemplate

struct PartTemplate {
    let name: String
    let category: String
    let intervalKm: Int32
    let intervalMonths: Int32
    let intervalYears: Int32
    let isCritical: Bool
    let notes: String
    let forYear2000: Bool
    let forYear2011: Bool

    init(
        _ name: String,
        category: String,
        km: Int32 = 0,
        months: Int32 = 0,
        years: Int32 = 0,
        critical: Bool = false,
        notes: String = "",
        both: Bool = true,
        only2000: Bool = false,
        only2011: Bool = false
    ) {
        self.name           = name
        self.category       = category
        self.intervalKm     = km
        self.intervalMonths = months
        self.intervalYears  = years
        self.isCritical     = critical
        self.notes          = notes
        self.forYear2000    = both || only2000
        self.forYear2011    = both || only2011
    }
}

